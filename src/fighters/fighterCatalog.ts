export type FighterEra =
  "World War II" | "Early jet age" | "Cold War" | "Modern";

export type FighterPropulsion = "piston" | "rocket" | "turbojet" | "turbofan";

export type FighterRole =
  | "day fighter"
  | "night fighter"
  | "interceptor"
  | "escort fighter"
  | "naval fighter"
  | "air superiority"
  | "multirole"
  | "light fighter"
  | "fighter-bomber";

