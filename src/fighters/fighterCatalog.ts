  "historic" | "operational" | "limited service" | "prototype / development";

export type FighterVisualFamily =
  | "biplane"
  | "inline-prop"
  | "radial-prop"
  | "twin-prop"
  | "twin-boom-prop"
  | "push-pull-prop"
