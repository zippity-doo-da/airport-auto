export const FIGHTER_CATALOG: readonly FighterProfile[] = [
  ...WWII,
  ...EARLY_JETS,
  ...COLD_WAR,
  ...MODERN,
].sort((a, b) => a.firstFlight - b.firstFlight || a.name.localeCompare(b.name));

export const FIGHTER_ERAS: readonly FighterEra[] = [
  "World War II",
  "Early jet age",
  "Cold War",
  "Modern",
];

export function fighterById(id: string): FighterProfile | undefined {
  return FIGHTER_CATALOG.find((fighter) => fighter.id === id);
}

export function fighterCatalogStats(): {
  airframes: number;
  nations: number;
  variants: number;
  wwii: number;
  jets: number;
} {
  return {
    airframes: FIGHTER_CATALOG.length,
    nations: new Set(FIGHTER_CATALOG.map((fighter) => fighter.designNation))
      .size,
    variants: FIGHTER_CATALOG.reduce(
      (total, fighter) => total + Math.max(1, fighter.variants.length),
      0,
    ),
    wwii: FIGHTER_CATALOG.filter((fighter) => fighter.era === "World War II")
      .length,
    jets: FIGHTER_CATALOG.filter((fighter) => fighter.propulsion !== "piston")
      .length,
  };
}

export function fighterCatalogValidationIssues(): string[] {
  const issues: string[] = [];
  const ids = new Set<string>();
  for (const fighter of FIGHTER_CATALOG) {
    if (ids.has(fighter.id)) issues.push(`Duplicate fighter id: ${fighter.id}`);
    ids.add(fighter.id);
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(fighter.id)) {
      issues.push(`Invalid fighter id: ${fighter.id}`);
    }
    if (fighter.lengthM <= 0 || fighter.wingspanM <= 0) {
      issues.push(`${fighter.id}: dimensions must be positive`);
    }
    if (fighter.maxSpeedKph <= 0 || fighter.serviceCeilingM <= 0) {
      issues.push(`${fighter.id}: performance envelope must be positive`);
    }
    if (fighter.engines < 1 || fighter.crew < 1) {
      issues.push(`${fighter.id}: engines and crew must be positive`);
    }
    for (const referenceId of fighter.referenceIds) {
      if (!FIGHTER_DATA_REFERENCES[referenceId]) {
        issues.push(`${fighter.id}: unknown reference ${referenceId}`);
      }
    }
  }
  return issues;
}

const CATALOG_ISSUES = fighterCatalogValidationIssues();
if (CATALOG_ISSUES.length > 0) {
  throw new Error(`Invalid fighter catalog:\n${CATALOG_ISSUES.join("\n")}`);
}
