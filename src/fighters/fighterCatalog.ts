interface FighterOptions {
  role?: FighterRole;
  status?: FighterStatus;
  variants?: string[];
  operators?: string[];
  summary?: string;
  references?: string[];
  visual?: Partial<FighterVisualDesign>;
}

function design(
  family: FighterVisualFamily,
  wing: WingPlanform,
  tail: FighterTail,
  intake: FighterIntake,
  sweepDeg: number,
  extras: Partial<FighterVisualDesign> = {},
): FighterVisualDesign {
  return { family, wing, tail, intake, sweepDeg, ...extras };
}

function f(
  id: string,
  name: string,
  manufacturer: string,
  designNation: string,
  firstFlight: number,
  era: FighterEra,
  propulsion: FighterPropulsion,
  lengthM: number,
  wingspanM: number,
  maxSpeedKph: number,
  serviceCeilingM: number,
  engines: number,
  crew: number,
  baseVisual: FighterVisualDesign,
  options: FighterOptions = {},
): FighterProfile {
  const status =
    options.status ?? (era === "Modern" ? "operational" : "historic");
  const role = options.role ?? defaultRole(era, baseVisual, crew);
  return {
    id,
    name,
    manufacturer,
    designNation,
    firstFlight,
    era,
    propulsion,
    role,
    status,
    lengthM,
    wingspanM,
    maxSpeedKph,
    serviceCeilingM,
    engines,
    crew,
    visual: { ...baseVisual, ...options.visual },
    variants: options.variants ?? [],
    operators: options.operators ?? [designNation],
    summary:
      options.summary ??
      `${designNation} ${role} first flown in ${firstFlight}.`,
    referenceIds: options.references ?? referencesFor(designNation, era),
  };
}

function defaultRole(
  era: FighterEra,
  visual: FighterVisualDesign,
  crew: number,
): FighterRole {
  if (crew > 1 && era === "World War II") return "night fighter";
  if (visual.naval) return "naval fighter";
  if (era === "Modern") return "multirole";
  if (era === "Cold War" || era === "Early jet age") return "interceptor";
  return "day fighter";
}

function referencesFor(nation: string, era: FighterEra): string[] {
  if (era === "Modern") {
    if (nation === "France") return ["dassault"];
    if (nation === "Sweden") return ["saab"];
    if (nation === "India") return ["hal"];
    if (nation === "European consortium") return ["eurofighter"];
    if (nation === "United States") return ["f35-program", "boeing-fighters"];
  }
  if (nation === "United Kingdom") return ["raf-museum"];
  if (nation === "United States") return ["usaf-museum", "smithsonian"];
  return ["smithsonian", "raf-museum"];
}

